"""Generates docs/CHECKS.md from `audit/catalog.yaml` and `audit/data/ai_bots.json`.

python -m searchos.audit.gen_docs           # write docs/CHECKS.md
python -m searchos.audit.gen_docs --check   # exit 1 if the file is out of date
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

from searchos.audit.ai_bots import load_ai_bots
from searchos.audit.catalog import SEVERITY_WEIGHTS, CheckInfo, load_catalog
from searchos.audit.model import CATEGORIES, Severity

CATEGORY_TITLES = {
    "indexability": "Indexability and crawling",
    "on_page": "On-page content",
    "structured_data": "Structured data",
    "performance": "Performance",
    "ai_readiness": "AI readiness",
}
SEVERITY_ORDER: list[Severity] = ["critical", "high", "medium", "low", "info"]
DOCS_PATH = Path(__file__).resolve().parents[3] / "docs" / "CHECKS.md"


def render() -> str:
    catalog = load_catalog()
    lines = [
        "# Audit checks",
        "",
        "<!-- Generated by `python -m searchos.audit.gen_docs` from backend/searchos/audit/catalog.yaml. "
        "Do not edit by hand. -->",
        "",
        f"The audit runs {len(catalog)} checks over everything the crawler found. "
        f"Each check belongs to one of {len(CATEGORIES)} categories and has a severity.",
        "",
        "## How the score works",
        "",
        "For every check that applied to something on the site, take the share of items that failed it "
        "(for a site-wide check that is 0 or 1). Weight each check by its severity and average:",
        "",
        "    score = 100 x (1 - sum(weight x failing share) / sum(weight))",
        "",
        "| Severity | Weight |",
        "| --- | --- |",
        *[f"| {s} | {SEVERITY_WEIGHTS[s]} |" for s in SEVERITY_ORDER],
        "",
        "A check that applies to nothing (for example the article checks on a site with no articles) is left "
        "out. Info checks are reported but do not change the score. Each category has its own subscore "
        "computed the same way over that category's checks. When nothing can be scored the score is shown as "
        "not available instead of 100.",
        "",
    ]
    for category in CATEGORIES:
        checks: list[CheckInfo] = [c for c in catalog.values() if c.category == category]
        checks.sort(key=lambda c: (SEVERITY_ORDER.index(c.severity), c.id))
        lines += [f"## {CATEGORY_TITLES[category]}", ""]
        for check in checks:
            lines += [
                f"### `{check.id}` - {check.title}",
                "",
                f"Severity: **{check.severity}** (weight {check.weight}). Applies to: `{check.applies_to}`.",
                "",
                f"**Why it matters.** {check.why_it_matters}",
                "",
                f"**How to fix it.** {check.how_to_fix}",
                "",
            ]
    lines += [
        "## AI crawlers checked in robots.txt",
        "",
        "Blocking a search or user-fetch bot is a high-severity issue because the site can then not appear "
        "in that assistant's answers. Blocking a training bot is only information: it is a choice.",
        "",
        "| User-agent | Vendor | Purpose | Verified on | Source |",
        "| --- | --- | --- | --- | --- |",
    ]
    for bot in load_ai_bots():
        verified = bot.verified_on or "not yet verified"
        lines.append(f"| `{bot.name}` | {bot.vendor} | {bot.purpose} | {verified} | {bot.source_url} |")
    lines.append("")
    return "\n".join(lines)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="fail if docs/CHECKS.md is out of date")
    args = parser.parse_args(argv)
    text = render()
    if args.check:
        current = DOCS_PATH.read_text(encoding="utf-8") if DOCS_PATH.exists() else ""
        if current != text:
            print("docs/CHECKS.md is out of date; run: python -m searchos.audit.gen_docs", file=sys.stderr)
            return 1
        return 0
    DOCS_PATH.write_text(text, encoding="utf-8")
    print(f"wrote {DOCS_PATH}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
