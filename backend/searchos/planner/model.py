"""Plain data the planner works on. No database or network types: builders are pure functions of these."""

from __future__ import annotations

import dataclasses as dc
from dataclasses import dataclass
from typing import Any

from searchos.stats.ctr_curve import CtrCurve


@dataclass(frozen=True, slots=True)
class GscQuery:
    query: str
    impressions: int
    clicks: int
    position: float


@dataclass(slots=True)
class GscPage:
    """Search Console numbers of one page over the newest 28 stored days (conversational queries excluded)."""

    impressions: int = 0
    clicks: int = 0
    queries: list[GscQuery] = dc.field(default_factory=list)  # best first (impressions)

    @property
    def top_query(self) -> GscQuery | None:
        return self.queries[0] if self.queries else None


@dataclass(frozen=True, slots=True)
class PlanPage:
    """One page of the latest crawl."""

    id: str
    url: str  # normalised
    status_code: int | None
    final_url: str | None
    redirect_chain: tuple[dict[str, Any], ...]
    title: str | None
    meta_description: str | None
    h1: tuple[str, ...]
    canonical: str | None
    word_count: int
    depth: int | None
    inlinks: int
    in_sitemap: bool
    is_indexable: bool
    is_success_html: bool
    text: str  # main text, first 6,000 characters ("" when this crawl did not store it)
    images: tuple[dict[str, Any], ...]
    h2: tuple[str, ...]
    jsonld: tuple[dict[str, Any], ...]
    jsonld_errors: tuple[str, ...]
    extra: dict[str, Any]

    @property
    def has_text(self) -> bool:
        return bool(self.text.strip())


@dataclass(frozen=True, slots=True)
class Finding:
    """An audit issue or a Search Console opportunity, ready for the builders."""

    source: str  # audit check id or opportunity type
    kind: str  # "audit" | "gsc"
    url: str | None  # the crawled page it belongs to (None = site-wide, or not in the crawl)
    details: dict[str, Any]
    query: str | None = None
    score: float = 0.0
    raw_url: str | None = None  # the URL as Search Console reported it


@dataclass(slots=True)
class Candidate:
    """What a builder wants to exist. The engine turns it into (or merges it with) an `actions` row."""

    type: str
    target_url: str | None
    field: str
    source_kind: str  # audit | gsc | site
    sources: list[str]
    current_value: Any = None
    proposed_value: Any = None  # deterministic value; None = to be generated by the AI (value_kind "ai")
    evidence: dict[str, Any] = dc.field(default_factory=dict)
    # Inputs of the expected-gain estimate (see planner/gain.py); `gain_clicks` is a Search-Console-based figure.
    gain_clicks: float | None = None
    impressions: int = 0

    @property
    def key(self) -> tuple[str, str, str]:
        return (self.type, self.target_url or "", self.field)


@dataclass(slots=True)
class PlanContext:
    site_id: str
    org_id: str
    domain: str
    site_name: str
    origin: str  # https://example.com (the homepage origin)
    homepage_url: str | None
    pages: dict[str, PlanPage]  # by normalised URL
    findings: list[Finding]
    gsc: dict[str, GscPage]  # by match_key(url)
    curve: CtrCurve | None
    has_audit: bool
    has_gsc: bool
    crawl_id: str | None = None
    robots_text: str | None = None
    # target URL -> URLs of crawled pages that already link to it (loaded for pages that need inbound links).
    linked_from: dict[str, frozenset[str]] = dc.field(default_factory=dict)
    # Findings the builders could not turn into an action, with the reason (shown in the plan summary).
    skipped: list[dict[str, Any]] = dc.field(default_factory=list)

    def page(self, url: str | None) -> PlanPage | None:
        return self.pages.get(url) if url else None
